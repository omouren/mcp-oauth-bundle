<?php

declare(strict_types=1);

use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $definition): void {
    $definition
        ->rootNode()
            ->children()
                ->scalarNode('authorization_prefix')
                    ->defaultValue('/oauth2')
                    ->cannotBeEmpty()
                ->end()
                ->arrayNode('scopes')
                    ->scalarPrototype()->end()
                    ->defaultValue(['mcp'])
                    ->info('Advertised scopes_supported, and the scopes that mark authorize/token as MCP when RFC 8707 resource is absent.')
                ->end()
                ->scalarNode('login_route')
                    ->isRequired()
                    ->cannotBeEmpty()
                    ->info('Symfony route name for the application login page, not a URL.')
                ->end()
                ->scalarNode('redirect_query_param')
                    ->defaultValue('_target_path')
                    ->cannotBeEmpty()
                    ->info('Query parameter appended to the login URL with the MCP authorize request URI. Symfony form_login uses _target_path.')
                ->end()
                ->enumNode('consent')
                    ->values(['page', 'auto'])
                    ->defaultValue('page')
                ->end()
                ->arrayNode('cimd')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultTrue()->end()
                        ->arrayNode('trusted_domains')
                            ->scalarPrototype()->end()
                            ->defaultValue(['claude.ai', 'vscode.dev', 'cursor.com'])
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('dcr')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultTrue()->end()
                        ->arrayNode('redirect_uri_schemes')
                            ->info('Custom (non-http) redirect URI schemes accepted at registration, e.g. native app schemes like "com.example.app". https and loopback http are always accepted.')
                            ->scalarPrototype()
                                ->validate()
                                    ->ifTrue(static fn (mixed $scheme): bool => !\is_string($scheme)
                                        || 1 !== preg_match('/^[a-z][a-z0-9+.-]*$/', $scheme)
                                        || \in_array($scheme, ['http', 'https', 'javascript', 'data', 'file', 'vbscript', 'blob', 'about'], true))
                                    ->thenInvalid('Invalid DCR redirect URI scheme %s: use a lowercase custom scheme; http, https, javascript, data, file, vbscript, blob and about are not allowed.')
                                ->end()
                            ->end()
                            ->defaultValue([])
                        ->end()
                        ->scalarNode('rate_limiter')
                            ->defaultNull()
                            ->info('Name of a framework.rate_limiter limiter applied to registrations per client IP. Requires symfony/rate-limiter.')
                        ->end()
                    ->end()
                ->end()
                ->booleanNode('resource_indicators')->defaultTrue()->end()
                ->booleanNode('issuer_identification')->defaultTrue()->end()
                ->scalarNode('public_base_url')
                    ->defaultNull()
                    ->info('Absolute origin used as OAuth issuer and MCP resource base. Defaults to the current request.')
                ->end()
            ->end()
        ->end()
    ;
};
